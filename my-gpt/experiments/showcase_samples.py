"""Generate side-by-side text samples from four points in the lineage for the showcase.

Writes docs/showcase_samples.md. Every model gets the same seed, sampling at
temperature 1 (no tricks), and the prompt "ROMEO" in its own corpus's speaker format.
Runs on the CPU so the samples reproduce exactly.
"""

from __future__ import annotations

import importlib.util
import sys
from pathlib import Path
from typing import Any

import torch

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from data_utils import CharacterData  # noqa: E402

OUT_PATH = ROOT / "docs" / "showcase_samples.md"
CHECKPOINTS = ROOT / "checkpoints"
TINY_PATH = ROOT / "data" / "input.txt"
NEW_CHARACTERS = 500
SAMPLE_SEED = 2026


def _load(name: str, filename: str) -> Any:
    spec = importlib.util.spec_from_file_location(name, ROOT / filename)
    assert spec is not None and spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    sys.modules[spec.name] = module
    spec.loader.exec_module(module)
    return module


_STAGE_14 = _load("stage_14_for_showcase", "14_dropout.py")
_STAGE_56 = _load("stage_56_for_showcase", "56_learning_rate_width.py")
_STAGE_51 = _STAGE_56._STAGE_51
_STAGE_41 = _STAGE_51._STAGE_41


def tiny_model(state: dict, block_size: int, n_embd: int, n_layer: int, vocab: int) -> torch.nn.Module:
    model = _STAGE_14.GPTLanguageModel(vocab, block_size, n_embd, n_head=4, n_layer=n_layer)
    if state:
        model.load_state_dict(state, strict=True)
    return model.eval()


def sample(model: torch.nn.Module, data: CharacterData, prompt: str) -> str:
    idx = torch.tensor([data.vocabulary.encode(prompt)], dtype=torch.long)
    torch.manual_seed(SAMPLE_SEED)
    out = model.generate(idx, max_new_tokens=NEW_CHARACTERS)
    return data.vocabulary.decode(out[0].tolist())


def main() -> None:
    torch.set_num_threads(1)  # other jobs often saturate the CPU; one thread avoids contention
    tiny = CharacterData.from_file(TINY_PATH)
    complete = CharacterData.from_file(_STAGE_41.DEFAULT_COMPLETE_DATA_PATH)
    stage_26 = torch.load(CHECKPOINTS / "stage_26_context_128_best_checkpoint.pt", map_location="cpu", weights_only=False)
    torch.manual_seed(0)
    entries = [
        ("Untrained (random weights)", "Same shape as Stage 10, before any training.", "n/a",
         tiny, "ROMEO:\n", tiny_model({}, 64, 64, 4, tiny.vocabulary.size)),
        ("Stage 10: first proper transformer", "4 layers, width 64, 64-character context. TinyShakespeare.", "1.68",
         tiny, "ROMEO:\n", tiny_model(torch.load(CHECKPOINTS / "stage_10_best_model.pt", map_location="cpu"),
                                      64, 64, 4, tiny.vocabulary.size)),
        ("Stage 26: best TinyShakespeare model", "6 layers, width 128, 128-character context, dropout.", "1.47",
         tiny, "ROMEO:\n", tiny_model(stage_26["model_state_dict"], 128, 128, 6, tiny.vocabulary.size)),
    ]
    champion, _ = _STAGE_51.load_endpoint(
        complete, CHECKPOINTS / "stage_53_c320_l6_p015_seed0_final_checkpoint.pt", torch.device("cpu")
    )
    entries.append(
        ("Stage 53: final champion", "6 layers, width 320, 256-character context. Complete Shakespeare.", "1.35",
         complete, "ROMEO.\n", champion.eval())
    )

    lines = [
        "# What the model writes at each step",
        "",
        "Each model continues the same prompt, `ROMEO`, written in its own training text's",
        f"speaker format. All use sampling seed `{SAMPLE_SEED}`, temperature 1 and {NEW_CHARACTERS}",
        "new characters, with no cherry-picking. Generated by",
        "[`experiments/showcase_samples.py`](../experiments/showcase_samples.py).",
        "",
        "Validation loss is shown for scale (lower is better). The first three models were",
        "trained on TinyShakespeare and the last on Complete Shakespeare, so the last number",
        "is not directly comparable with the others.",
        "",
    ]
    for title, description, loss, data, prompt, model in entries:
        text = sample(model, data, prompt)
        print(f"{title}: {len(text)} characters", flush=True)
        lines += [f"## {title}", "", f"{description} Validation loss: {loss}.", "", "```text", text.rstrip(), "```", ""]
    OUT_PATH.write_text("\n".join(lines), encoding="utf-8")
    print(f"Wrote {OUT_PATH}")


if __name__ == "__main__":
    main()
